use super::RespUsage;
use serde::{Deserialize, Serialize};
use serde_json::Value;
use serde_with::skip_serializing_none;

/// DOC: https://platform.openai.com/docs/api-reference/responses/object
///
/// NOTE: Not all OpenAI Responses Response properties have been set in this struct.
///       Mostly what is needed for the Chat Completion compatibility.
#[skip_serializing_none]
#[derive(Default, Debug, Clone, Serialize, Deserialize)]
pub struct RespResponse {
	/// Unique identifier for this Response.
	pub id: String,

	/// The status of the response generation. One of completed, failed, in_progress, cancelled, queued, or incomplete.
	pub status: String,

	/// Why the response is `incomplete`: `{reason: "max_output_tokens" | "content_filter"}`.
	pub incomplete_details: Option<Value>,

	/// {code: String, message: string}
	pub error: Option<Value>,

	/// An upper bound for the number of tokens that can be generated for a response, including visible output tokens and reasoning tokens.
	pub max_output_tokens: Option<i64>,

	/// Model ID used to generate the response, like gpt-4o or o3.
	pub model: String,

	/// An array of content items generated by the model.
	///
	/// `#[serde(default)]` is required because some Responses-API-compatible
	/// backends omit this field entirely from the terminal `response.completed`
	/// event. Without the default, the whole event fails to deserialize and the
	/// streamer skips it, dropping tool calls that were accumulated from the
	/// preceding `response.function_call_arguments.delta` events.
	#[serde(default)]
	pub output: Vec<Value>,

	pub usage: Option<RespUsage>,
}

impl RespResponse {
	/// The provider stop reason: for an `incomplete` response, the reason it was cut short
	/// (`max_output_tokens`, `content_filter`) when given, otherwise the response status.
	pub fn stop_reason_raw(&self) -> String {
		if self.status == "incomplete"
			&& let Some(reason) = self
				.incomplete_details
				.as_ref()
				.and_then(|details| details.get("reason"))
				.and_then(Value::as_str)
		{
			return reason.to_string();
		}
		self.status.clone()
	}
}
